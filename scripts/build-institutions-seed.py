"""Build seed SQL for the `institutions` table from the CSV export.

Usage:
    python scripts/build-institutions-seed.py <csv file or folder> [...] <output.sql>

Each input is a `;`-separated UTF-8 CSV (BOM allowed) with the columns of the
original export. A folder means every *.csv inside it. Preschools are skipped.

The output is one upsert per institution keyed on reg_number, so it can be run
again after a newer export. Existing slugs are never changed (URLs stay stable).

Keep normalize() and slugify() in sync with src/lib/slug.ts.
"""

import csv
import re
import sys
import unicodedata
from collections import defaultdict
from pathlib import Path

EXCLUDED_VEIDI = {"Pirmsskolas izglītības iestāde"}

COLUMNS = {
    "name": "Iestādes nosaukums",
    "veids": "Veids",
    "tips": "Tips",
    "founder": "Dibinātājs",
    "liquidated": "Likvidēta",
    "accredited": "Akreditēta",
    "reg_number": "Reģistrācijas numurs",
    "subordination": "Pakļautība",
    "location": "Atrašanās vieta",
}

# The export uses this placeholder for unknown values (873 locations); store NULL.
MISSING_MARKERS = {"-Nav norādīts-"}

QUOTES ="\"'„“”«»‘’`"


def normalize(text: str) -> str:
    """Lowercase, strip diacritics and quotes, collapse whitespace (for search)."""
    text = unicodedata.normalize("NFKD", text.lower())
    text = "".join(c for c in text if not unicodedata.combining(c) and c not in QUOTES)
    return re.sub(r"\s+", " ", text).strip()


def slugify(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", normalize(text)).strip("-")


def yes_no(value: str, column: str, reg: str) -> int:
    value = value.strip()
    if value == "Jā":
        return 1
    if value == "Nē":
        return 0
    raise ValueError(f"{reg}: unexpected {column} value {value!r}")


def sql_str(value):
    if value is None or value == "":
        return "NULL"
    return "'" + str(value).replace("'", "''") + "'"


def read_rows(paths):
    rows = []
    for path in paths:
        with open(path, encoding="utf-8-sig", newline="") as f:
            reader = csv.DictReader(f, delimiter=";")
            missing = set(COLUMNS.values()) - set(reader.fieldnames or [])
            if missing:
                raise ValueError(f"{path}: missing columns {sorted(missing)}")
            rows.extend(reader)
    return rows


def main(argv):
    if len(argv) < 3:
        print(__doc__)
        return 2
    *inputs, output = argv[1:]

    paths = []
    for item in inputs:
        p = Path(item)
        paths.extend(sorted(p.glob("*.csv")) if p.is_dir() else [p])
    if not paths:
        raise SystemExit("No CSV files found")

    institutions = {}
    skipped = 0
    for row in read_rows(paths):
        row = {k: (row[v] or "").strip() for k, v in COLUMNS.items()}
        row = {k: "" if v in MISSING_MARKERS else v for k, v in row.items()}
        if row["veids"] in EXCLUDED_VEIDI:
            skipped += 1
            continue
        reg = row["reg_number"]
        if not reg or not row["name"]:
            raise ValueError(f"Row without name or registration number: {row}")
        if reg in institutions:
            raise ValueError(f"Duplicate registration number {reg}")
        row["accredited"] = yes_no(row["accredited"], "Akreditēta", reg)
        row["liquidated"] = yes_no(row["liquidated"], "Likvidēta", reg)
        row["name_search"] = normalize(row["name"])
        institutions[reg] = row

    # Slugs: if several institutions share a name, all of them get the location
    # appended; if that still collides, the registration number. This depends
    # only on the set of rows, not their order.
    by_slug = defaultdict(list)
    for inst in institutions.values():
        by_slug[slugify(inst["name"])].append(inst)
    for base, group in by_slug.items():
        for inst in group:
            suffix = slugify(inst["location"]) if inst["location"] else inst["reg_number"]
            inst["slug"] = base if len(group) == 1 else f"{base}-{suffix}"
    by_slug = defaultdict(list)
    for inst in institutions.values():
        by_slug[inst["slug"]].append(inst)
    for slug, group in by_slug.items():
        if len(group) > 1:
            for inst in group:
                inst["slug"] = f"{slug}-{inst['reg_number']}"

    cols = ["reg_number", "name", "name_search", "slug", "veids", "tips", "founder",
            "accredited", "liquidated", "subordination", "location"]
    updatable = [c for c in cols if c not in ("reg_number", "slug")]

    lines = [
        "-- Generated by scripts/build-institutions-seed.py. Do not edit by hand.",
        f"-- {len(institutions)} institutions ({skipped} preschools skipped)",
    ]
    for reg in sorted(institutions):
        inst = institutions[reg]
        values = ", ".join(
            str(inst[c]) if isinstance(inst[c], int) else sql_str(inst[c]) for c in cols
        )
        updates = ", ".join(f"{c} = excluded.{c}" for c in updatable)
        lines.append(
            f"INSERT INTO institutions ({', '.join(cols)}) VALUES ({values}) "
            f"ON CONFLICT(reg_number) DO UPDATE SET {updates}, updated_at = datetime('now');"
        )

    out = Path(output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {len(institutions)} institutions to {out} ({skipped} preschools skipped)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
